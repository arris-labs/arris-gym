#!/usr/bin/env python3
"""Generate docs/ARRIS_API.md from the installed arris wheel's own sources.

The stubs (`_arris.pyi`) and `arris/build/*.py` are read as text through their
AST, never imported, so the reference says what the wheel declares. Private
names are left out. The output depends on the wheel alone, so the gate can
compare it: an arris bump regenerates this file in the same commit.

Usage: tools/gen_arris_api.py [--check]
With --check, writes nothing and exits 1 if the file differs.
"""

import argparse
import ast
import importlib.metadata
import importlib.util
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "docs" / "ARRIS_API.md"


def public(name: str) -> bool:
    """Whether a name is part of the public surface; dunders are left out too."""
    return not name.startswith("_")


def signature(node: ast.FunctionDef) -> str:
    """One line for a function, without its body."""
    decorators = [ast.unparse(d) for d in node.decorator_list]
    prefix = "".join(f"@{d} " for d in decorators if d != "final")
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"{prefix}def {node.name}({ast.unparse(node.args)}){returns}"


def first_line(node: ast.ClassDef | ast.FunctionDef) -> str:
    """The first line of a docstring, or nothing."""
    doc = ast.get_docstring(node)
    return doc.splitlines()[0] if doc else ""


def is_error(node: ast.ClassDef) -> bool:
    """Whether a class derives from an exception, by its bases' names."""
    bases = [ast.unparse(b) for b in node.bases]
    return any(b.endswith("Error") or b in ("Exception", "InterruptedError") for b in bases)


def members(node: ast.ClassDef) -> list[str]:
    """A class's public functions and annotated fields, one line each."""
    lines = []
    for item in node.body:
        if isinstance(item, ast.FunctionDef) and (public(item.name) or item.name == "__init__"):
            lines.append(signature(item))
        elif (
            isinstance(item, ast.AnnAssign)
            and isinstance(item.target, ast.Name)
            and public(item.target.id)
        ):
            lines.append(ast.unparse(item))
    return lines


def render_class(node: ast.ClassDef) -> list[str]:
    """A class as a heading and a code block."""
    bases = ", ".join(ast.unparse(b) for b in node.bases)
    title = f"### `{node.name}({bases})`" if bases else f"### `{node.name}`"
    out = [title, ""]
    if first_line(node):
        out += [first_line(node), ""]
    lines = members(node)
    if lines:
        out += ["```python", *lines, "```", ""]
    return out


def render_errors(nodes: list[ast.ClassDef]) -> list[str]:
    """The exception tree as a table: a refusal's kind is its class name."""
    out = ["| Exception | Base | Fields |", "|---|---|---|"]
    for node in nodes:
        fields = ", ".join(
            ast.unparse(i).replace("|", "\\|") for i in node.body if isinstance(i, ast.AnnAssign)
        )
        bases = ", ".join(ast.unparse(b) for b in node.bases)
        out.append(f"| `{node.name}` | `{bases}` | {fields} |")
    return [*out, ""]


def render_module(tree: ast.Module) -> tuple[list[str], list[ast.ClassDef]]:
    """A module's public functions and classes, and its exceptions set apart."""
    out: list[str] = []
    errors = []
    functions = [n for n in tree.body if isinstance(n, ast.FunctionDef) and public(n.name)]
    if functions:
        out += ["```python", *[signature(f) for f in functions], "```", ""]
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and public(node.name):
            if is_error(node):
                errors.append(node)
            else:
                out += render_class(node)
    return out, errors


def parse(path: pathlib.Path) -> ast.Module:
    """A source file's AST."""
    return ast.parse(path.read_text(encoding="utf-8"))


def generate() -> str:
    """The whole reference, from the installed wheel."""
    spec = importlib.util.find_spec("arris")
    if spec is None or spec.origin is None:
        raise SystemExit("arris is not installed: uv sync")
    root = pathlib.Path(spec.origin).parent
    version = importlib.metadata.version("arris")
    out = [
        "# arris API",
        "",
        f"Generated by `tools/gen_arris_api.py` from arris {version}: never edit by hand.",
        "",
        "## `arris`",
        "",
    ]
    body, errors = render_module(parse(root / "_arris.pyi"))
    out += body
    build: list[str] = []
    for path in sorted((root / "build").glob("*.py")):
        if path.name != "__init__.py":
            more, more_errors = render_module(parse(path))
            build += more
            errors += more_errors
    out += ["## `arris.build`", "", *build, "## Exceptions", "", *render_errors(errors)]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    text = generate()
    if parser.parse_args().check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} differs from the wheel: tools/gen_arris_api.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
